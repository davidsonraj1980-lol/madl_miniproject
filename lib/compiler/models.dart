/// Hardware ALU and Transistor Simulation State
class HardwareState {
  final int r0Val;
  final int r1Val;
  final int accVal;
  final bool carryFlag;
  final bool zeroFlag;
  final bool overflowFlag;
  final String operation; // 'ADD', 'SUB', 'AND', 'OR', 'XOR'
  final int activeBitSlice; // 0..7

  const HardwareState({
    this.r0Val = 10,
    this.r1Val = 5,
    this.accVal = 15,
    this.carryFlag = false,
    this.zeroFlag = false,
    this.overflowFlag = false,
    this.operation = 'ADD',
    this.activeBitSlice = 0,
  });

  HardwareState copyWith({
    int? r0Val,
    int? r1Val,
    int? accVal,
    bool? carryFlag,
    bool? zeroFlag,
    bool? overflowFlag,
    String? operation,
    int? activeBitSlice,
  }) {
    return HardwareState(
      r0Val: r0Val ?? this.r0Val,
      r1Val: r1Val ?? this.r1Val,
      accVal: accVal ?? this.accVal,
      carryFlag: carryFlag ?? this.carryFlag,
      zeroFlag: zeroFlag ?? this.zeroFlag,
      overflowFlag: overflowFlag ?? this.overflowFlag,
      operation: operation ?? this.operation,
      activeBitSlice: activeBitSlice ?? this.activeBitSlice,
    );
  }

  /// Converts an 8-bit integer into a list of 8 bits (MSB at index 7, LSB at index 0)
  static List<int> to8BitArray(int value) {
    final clamped = value.clamp(0, 255);
    final bits = <int>[];
    for (int i = 0; i < 8; i++) {
      bits.add((clamped >> i) & 1);
    }
    return bits; // index 0 = bit 0 (LSB), index 7 = bit 7 (MSB)
  }

  List<int> get r0Bits => to8BitArray(r0Val);
  List<int> get r1Bits => to8BitArray(r1Val);
  List<int> get accBits => to8BitArray(accVal);

  /// Computes full adder state for bit slice [bitIndex]
  FullAdderState getBitSliceState(int bitIndex) {
    final idx = bitIndex.clamp(0, 7);
    int cIn = 0;
    // Calculate ripple carry up to bitIndex
    for (int i = 0; i < idx; i++) {
      final a = (r0Val >> i) & 1;
      final b = (r1Val >> i) & 1;
      final ha1Sum = a ^ b;
      final ha1Carry = a & b;
      final ha2Carry = ha1Sum & cIn;
      cIn = ha1Carry | ha2Carry;
    }

    final aBit = (r0Val >> idx) & 1;
    final bBit = (r1Val >> idx) & 1;
    return FullAdderState(
      bitIndex: idx,
      aBit: aBit,
      bBit: bBit,
      cIn: cIn,
    );
  }
}

/// Logic Gate & Transistor state for a 1-bit Full Adder
class FullAdderState {
  final int bitIndex;
  final int aBit;
  final int bBit;
  final int cIn;

  const FullAdderState({
    required this.bitIndex,
    required this.aBit,
    required this.bBit,
    required this.cIn,
  });

  // Half Adder 1 (inputs: A, B)
  int get halfAdder1Sum => aBit ^ bBit;
  int get halfAdder1Carry => aBit & bBit;

  // Half Adder 2 (inputs: HA1Sum, C_in)
  int get sum => halfAdder1Sum ^ cIn;
  int get halfAdder2Carry => halfAdder1Sum & cIn;

  // Final Carry Out
  int get cOut => halfAdder1Carry | halfAdder2Carry;
}
