/// Single Bytecode Instruction
class BytecodeInstruction {
  final int address;
  final BytecodeOpCode op;
  final dynamic arg;
  final String description;
  final String assemblyEquivalent;

  const BytecodeInstruction({
    required this.address,
    required this.op,
    this.arg,
    required this.description,
    required this.assemblyEquivalent,
  });

  String get formattedOp => arg != null ? '${op.name} $arg' : op.name;
}

/// Register-Based Assembly Instruction
class AssemblyInstruction {
  final String? label;
  final String mnemonic;
  final List<String> operands;
  final String comment;

  const AssemblyInstruction({
    this.label,
    required this.mnemonic,
    required this.operands,
    required this.comment,
  });

  String get formatted {
    final ops = operands.join(', ');
    final inst = ops.isNotEmpty ? '$mnemonic $ops' : mnemonic;
    if (label != null) {
      return '$label:\n    $inst';
    }
    return '    $inst';
  }
}

