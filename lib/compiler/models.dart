/// Supported Token Categories for Lexical Analysis
enum TokenType {
  keywordLet,
  keywordIf,
  keywordElse,
  keywordTrue,
  keywordFalse,
  identifier,
  numberLiteral,
  stringLiteral,
  opAssign,
  opPlus,
  opMinus,
  opMultiply,
  opDivide,
  opEqual,
  opNotEqual,
  opLessThan,
  opLessEqual,
  opGreaterThan,
  opGreaterEqual,
  opAnd,
  opOr,
  opNot,
  semicolon,
  openParen,
  closeParen,
  openBrace,
  closeBrace,
  comma,
  comment,
  eof,
  unknown,
}

/// Token object generated by Lexical Analyzer
class Token {
  final TokenType type;
  final String lexeme;
  final dynamic literal;
  final int line;
  final int column;
  final int startIndex;
  final int endIndex;
  final String explanation;

  const Token({
    required this.type,
    required this.lexeme,
    this.literal,
    required this.line,
    required this.column,
    required this.startIndex,
    required this.endIndex,
    required this.explanation,
  });

  String get typeName {
    switch (type) {
      case TokenType.keywordLet:
      case TokenType.keywordIf:
      case TokenType.keywordElse:
      case TokenType.keywordTrue:
      case TokenType.keywordFalse:
        return 'KEYWORD';
      case TokenType.identifier:
        return 'IDENTIFIER';
      case TokenType.numberLiteral:
        return 'NUMBER';
      case TokenType.stringLiteral:
        return 'STRING';
      case TokenType.opAssign:
        return 'ASSIGN';
      case TokenType.opPlus:
      case TokenType.opMinus:
      case TokenType.opMultiply:
      case TokenType.opDivide:
      case TokenType.opEqual:
      case TokenType.opNotEqual:
      case TokenType.opLessThan:
      case TokenType.opLessEqual:
      case TokenType.opGreaterThan:
      case TokenType.opGreaterEqual:
      case TokenType.opAnd:
      case TokenType.opOr:
      case TokenType.opNot:
        return 'OPERATOR';
      case TokenType.semicolon:
      case TokenType.openParen:
      case TokenType.closeParen:
      case TokenType.openBrace:
      case TokenType.closeBrace:
      case TokenType.comma:
        return 'PUNCTUATION';
      case TokenType.comment:
        return 'COMMENT';
      case TokenType.eof:
        return 'EOF';
      case TokenType.unknown:
        return 'UNKNOWN';
    }
  }

  Color get categoryColor {
    switch (typeName) {
      case 'KEYWORD':
        return const Color(0xFFFF007A); // Neon Pink
      case 'IDENTIFIER':
        return const Color(0xFF00E5FF); // Electric Cyan
      case 'NUMBER':
        return const Color(0xFFFFB300); // Amber
      case 'STRING':
        return const Color(0xFF00E676); // Spring Green
      case 'OPERATOR':
        return const Color(0xFFD500F9); // Vivid Violet
      case 'PUNCTUATION':
        return const Color(0xFF78909C); // Slate Blue-Grey
      default:
        return const Color(0xFF9E9E9E);
    }
  }

  @override
  String toString() => '$typeName("$lexeme") at $line:$column';
}

/// Primitive Data Types supported by CompileLens Toy Language
enum DataType {
  integer,
  float,
  boolean,
  string,
  voidType,
  unknown,
  error,
}

extension DataTypeExtension on DataType {
  String get displayName {
    switch (this) {
      case DataType.integer:
        return 'int';
      case DataType.float:
        return 'float';
      case DataType.boolean:
        return 'bool';
      case DataType.string:
        return 'string';
      case DataType.voidType:
        return 'void';
      case DataType.unknown:
        return 'unknown';
      case DataType.error:
        return 'error';
    }
  }

  Color get color {
    switch (this) {
      case DataType.integer:
        return const Color(0xFFFF9E0B);
      case DataType.float:
        return const Color(0xFFFFD54F);
      case DataType.boolean:
        return const Color(0xFF00E5FF);
      case DataType.string:
        return const Color(0xFF00FF88);
      case DataType.voidType:
        return const Color(0xFF9E9E9E);
      case DataType.unknown:
      case DataType.error:
        return const Color(0xFFFF5252);
    }
  }
}

/// Abstract Syntax Tree (AST) Base Node
abstract class ASTNode {
  final String id;
  final int line;
  final int column;
  DataType inferredType = DataType.unknown;
  dynamic evaluatedConstantValue;
  bool isConstantFoldable = false;

  ASTNode({
    required this.id,
    required this.line,
    required this.column,
  });

  String get nodeType;
  String get label;
  String get subtitle;
  String get grammarRule;
  String get explanation;
  List<ASTNode> get children;
  Color get themeColor;
}

/// Root AST Node representing entire script
class ProgramNode extends ASTNode {
  final List<ASTNode> statements;

  ProgramNode({
    required super.id,
    required super.line,
    required super.column,
    required this.statements,
  });

  @override
  String get nodeType => 'Program';

  @override
  String get label => 'Program (Root)';

  @override
  String get subtitle => '${statements.length} statements';

  @override
  String get grammarRule => 'Program -> Statement* EOF';

  @override
  String get explanation =>
      'Root node of the compilation compilation unit. Encapsulates top-level sequential execution blocks.';

  @override
  List<ASTNode> get children => statements;

  @override
  Color get themeColor => const Color(0xFF7C4DFF);
}

/// Variable Declaration Statement Node: `let x = 10;`
class VarDeclNode extends ASTNode {
  final String identifier;
  final ASTNode? initializer;
  final DataType declaredType;

  VarDeclNode({
    required super.id,
    required super.line,
    required super.column,
    required this.identifier,
    this.initializer,
    this.declaredType = DataType.unknown,
  });

  @override
  String get nodeType => 'VarDecl';

  @override
  String get label => 'let $identifier';

  @override
  String get subtitle =>
      initializer != null ? 'Init: ${initializer!.label}' : 'Uninitialized';

  @override
  String get grammarRule =>
      'VarDecl -> "let" IDENTIFIER ( "=" Expression )? ";"?';

  @override
  String get explanation =>
      'Allocates symbol "$identifier" in local scope memory and evaluates optional initial expression.';

  @override
  List<ASTNode> get children => initializer != null ? [initializer!] : [];

  @override
  Color get themeColor => const Color(0xFF00E5FF);
}

