/// Binary Expression Node: `left + right`
class BinaryExprNode extends ASTNode {
  final ASTNode left;
  final String operator;
  final ASTNode right;

  BinaryExprNode({
    required super.id,
    required super.line,
    required super.column,
    required this.left,
    required this.operator,
    required this.right,
  });

  @override
  String get nodeType => 'BinaryExpr';

  @override
  String get label => 'Op: $operator';

  @override
  String get subtitle =>
      isConstantFoldable && evaluatedConstantValue != null
          ? 'Folds to $evaluatedConstantValue'
          : 'Binary ($operator)';

  @override
  String get grammarRule {
    if (operator == '+' || operator == '-') {
      return 'Expr -> Term (("+" | "-") Term)*';
    } else if (operator == '*' || operator == '/') {
      return 'Term -> Factor (("*" | "/") Factor)*';
    } else {
      return 'Relational -> Expr (("<"|">"|"=="|"!=") Expr)*';
    }
  }

  @override
  String get explanation {
    if (operator == '*' || operator == '/') {
      return 'Multiplicative operator "$operator" binds tighter than additive operations due to grammar precedence rules.';
    } else if (operator == '+' || operator == '-') {
      return 'Additive operator "$operator" computed after sub-factors are reduced on the operand stack.';
    } else {
      return 'Comparison operator "$operator" yields a boolean result (1 or 0) comparing left and right operands.';
    }
  }

  @override
  List<ASTNode> get children => [left, right];

  @override
  Color get themeColor => const Color(0xFFE040FB);
}

