  IfNode({
    required super.id,
    required super.line,
    required super.column,
    required this.condition,
    required this.thenBranch,
    this.elseBranch,
  });

  @override
  String get nodeType => 'IfStatement';

  @override
  String get label => 'if (cond)';

  @override
  String get subtitle => elseBranch != null ? 'With Else' : 'Then Only';

  @override
  String get grammarRule =>
      'IfStmt -> "if" "(" Expression ")" Statement ( "else" Statement )?';

  @override
  String get explanation =>
      'Evaluates condition expression. If false, branch jump instruction alters instruction pointer (PC).';

